async page => {
  const base = 'http://127.0.0.1:4191';
  const results = [];
  const check = (ok, label) => { if (!ok) throw new Error(label); results.push(label); };
  await page.unrouteAll();
  await page.route('**/*', route => route.request().url().startsWith(base + '/') ? route.continue() : route.abort());
  await page.goto(base + '/calendar/new');
  await page.evaluate(() => sessionStorage.clear());
  await page.reload();
  await page.getByRole('textbox', { name: '행사 이름 (필수)' }).fill('합성 행사 홍보');
  await page.locator('.event-editor-more summary').click();
  const url = page.getByRole('textbox', { name: '게시물 또는 릴 URL' });
  await url.fill('https://www.instagram.com/p/ABCDE/?utm_source=synthetic');
  await page.getByRole('button', { name: '링크 연결', exact: true }).click();
  check(await page.getByRole('link', { name: '원문 열기' }).getAttribute('href') === 'https://www.instagram.com/p/ABCDE/', 'post URL remains a post and strips tracking');
  await page.reload();
  const resume = page.getByRole('button', { name: /계속 작성/ });
  if (await resume.count()) await resume.click();
  await page.locator('.event-editor-more summary').click();
  await page.getByRole('link', { name: '원문 열기' }).waitFor();
  check(await page.getByRole('link', { name: '원문 열기' }).getAttribute('href') === 'https://www.instagram.com/p/ABCDE/', 'Instagram attachment survives draft recovery');
  await page.getByRole('button', { name: 'Instagram 링크 제거', exact: true }).click();
  check(await page.getByRole('link', { name: '원문 열기' }).count() === 0, 'Instagram attachment can be removed');
  const thumbnailInput = page.locator('.event-editor-step > .event-file-picker input[type="file"]').first();
  await thumbnailInput.setInputFiles('output/playwright/event-presentation-0911.png');
  const preview = page.getByRole('img', { name: 'event-presentation-0911.png 미리보기' });
  await preview.waitFor();
  check(await thumbnailInput.inputValue() === '', 'file picker resets after consuming selection');
  check(await preview.evaluate(e => getComputedStyle(e).objectFit === 'contain'), 'selected image preview defaults to contain');
  await page.getByRole('combobox', { name: '사진 표시', exact: true }).selectOption('cover');
  check(await preview.evaluate(e => getComputedStyle(e).objectFit === 'cover'), 'image preview responds to cover choice');
  await page.getByRole('button', { name: 'event-presentation-0911.png 제거', exact: true }).click();
  check(await preview.count() === 0, 'selected image can be removed without uploading');
  await thumbnailInput.setInputFiles('output/playwright/event-presentation-0911.png');
  await preview.waitFor();
  check(await preview.isVisible(), 'same file can be selected again after removal');
  await page.goto(base + '/events/synthetic-event-0');
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => { throw new Error('synthetic denial'); } } }));
  await page.getByRole('button', { name: '행사 링크 복사', exact: true }).click();
  check(await page.getByRole('textbox', { name: '아래 주소를 직접 복사해 주세요' }).inputValue() === base + '/events/synthetic-event-0', 'clipboard denial offers canonical event URL');
  await page.evaluate(() => sessionStorage.clear());
  return { results, qualification: 'synthetic local form only; no real event created' };
}
